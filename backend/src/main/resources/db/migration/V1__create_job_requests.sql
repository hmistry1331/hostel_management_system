CREATE TABLE job_requests (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    worker_id BIGINT NULL,
    problem_description VARCHAR(2000) NOT NULL,
    category VARCHAR(30) NOT NULL,
    location_type VARCHAR(20) NOT NULL,
    block VARCHAR(100) NOT NULL,
    floor INT NULL,
    room_number VARCHAR(30) NULL,
    area_name VARCHAR(120) NULL,
    urgency VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    contact_number VARCHAR(30) NULL,
    before_image_url VARCHAR(500) NOT NULL,
    after_image_url VARCHAR(500) NULL,
    id_card_photo_url VARCHAR(500) NULL,
    not_solved_reason VARCHAR(30) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
    student_confirmation VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    rejection_reason VARCHAR(1000) NULL,
    upvote_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    completed_at TIMESTAMP(6) NULL,
    scheduled_slot_id BIGINT NULL,
    CONSTRAINT chk_job_location_type CHECK (location_type IN ('ROOM', 'COMMON_AREA')),
    CONSTRAINT chk_job_urgency CHECK (urgency IN ('NORMAL', 'URGENT')),
    INDEX idx_job_status_category_created (status, category, created_at),
    INDEX idx_job_customer_created (customer_id, created_at)
);
