import apiClient from './client'

export const getJobsForStudent = (customerId) => apiClient.get(`/jobs/customer/${customerId}`)
export const getJobsForAdmin = () => apiClient.get('/jobs/admin')
export const getJobsForWorker = () => apiClient.get('/jobs/worker')
export const createJobRequest = (payload) => apiClient.post('/jobs/create', payload)
export const findSimilarJobs = (payload) => apiClient.get('/jobs/similar', { params: payload })
export const cancelJobRequest = (jobId) => apiClient.put(`/jobs/${jobId}/cancel`)
export const startJobRequest = (jobId) => apiClient.put(`/jobs/${jobId}/start`)
export const completeJobRequest = (jobId, payload) => apiClient.post(`/jobs/${jobId}/complete`, payload)
export const notSolvedJobRequest = (jobId, payload) => apiClient.put(`/jobs/${jobId}/not-solved`, payload)
export const rejectJobCompletion = (jobId, payload) => apiClient.put(`/jobs/${jobId}/reject`, payload)
export const confirmJobCompletion = (jobId) => apiClient.put(`/jobs/${jobId}/confirm`)
export const getWorkerSchedule = () => apiClient.get('/worker/schedule/today')
export const getAdminSchedule = () => apiClient.get('/admin/schedule/today')
export const startJobForWorker = (jobId, workerId) => apiClient.put(`/jobs/admin/${jobId}/start`, null, { params: { workerId } })
export const completeJobForWorker = (jobId, workerId, payload) => apiClient.post(`/jobs/admin/${jobId}/complete`, payload, { params: { workerId } })
export const markJobNotSolvedForWorker = (jobId, workerId, payload) => apiClient.put(`/jobs/admin/${jobId}/not-solved`, payload, { params: { workerId } })
export const getEntryLog = (jobId) => apiClient.get(`/admin/jobs/${jobId}/entry-log`)
